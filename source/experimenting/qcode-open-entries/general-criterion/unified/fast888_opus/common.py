import hashlib
import json
import subprocess
from pathlib import Path
from model import lift_coordinate

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
S4 = ROOT / 'mixed_frames/stage4'
FROZEN = S4 / 'enumerate_z'
FAST = HERE / 'enumerate_fast'
TMP = HERE / 'tmp'
UNION = (2, 2, 1)  # max L, L6, L7 over profiles (1,0),(1,1),(2,0); identical mu=6, cut/w6/w7/nr
PROFILE_LINE = {'10': (1, 1, 0), '11': (2, 1, 1), '20': (2, 2, 0)}


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def manifest():
    return json.loads((S4 / 'manifest.json').read_text())


def case_lines(index, prof):
    return (S4 / f'inputs/888_{index}_{prof}.txt').read_text().splitlines()


def union_input(index):
    """Stage-4 profile inputs differ only in line 6; replace its budget by the union."""
    texts = {pf: case_lines(index, pf) for pf in PROFILE_LINE}
    base = texts['10']
    for pf, lines in texts.items():
        assert len(lines) == 7 and lines[:5] == base[:5] and lines[6] == base[6], (index, pf)
        head = list(map(int, lines[5].split()))
        assert tuple(head[:3]) == PROFILE_LINE[pf] and head[3:] == [8, 6, 7, 4], (index, pf, head)
        assert lines[0].split()[3] == '6'  # mu
    for pf in PROFILE_LINE:
        assert (S4 / f'inputs/888_{index}_{pf}.sym').read_bytes() == (S4 / f'inputs/888_{index}_10.sym').read_bytes()
    lines = list(base)
    lines[5] = ' '.join(map(str, [*UNION, 8, 6, 7, 4]))
    TMP.mkdir(exist_ok=True)
    path = TMP / f'union_{index}.txt'
    path.write_text('\n'.join(lines) + '\n')
    return path


def run(binary, inp, *args, timeout=25):
    cmd = [str(binary), str(inp), *map(str, args)]
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    assert proc.returncode == 0, (cmd, proc.returncode, proc.stderr)
    rows = [json.loads(l) for l in proc.stdout.splitlines()]
    assert rows and rows[-1]['type'] == 'summary' and sum(r['type'] == 'summary' for r in rows) == 1
    assert all(r['type'] == 'leaf' for r in rows[:-1])
    return dict(**rows[-1], leaves=[r['X'] for r in rows[:-1]])


def checkpoint(index, prof, first):
    folder = S4 / 'runs' / f'888_{index}_{prof}' / str(first)
    cp = json.loads((folder / 'checkpoint.json').read_text())
    if cp['status'] != 'COMPLETE':
        return None
    log = (folder / 'enumerator.jsonl').read_text()
    assert sha(folder / 'enumerator.jsonl') == cp['log_sha256']
    rows = [json.loads(l) for l in log.splitlines()]
    assert rows[-1] == cp['enumerator']
    return dict(cp=cp, leaves=[r['X'] for r in rows[:-1]], summary=rows[-1])


def group_closure(maps, b):
    """All syndrome maps a -> lift(a, S) generated by the certified generators."""
    N = 1 << b
    ident = tuple(range(N))
    gens = [tuple(lift_coordinate(a, S) for a in range(N)) for S in maps]
    seen = {ident}
    todo = [ident]
    while todo:
        g = todo.pop()
        for h in gens:
            k = tuple(h[g[a]] for a in range(N))
            if k not in seen:
                seen.add(k)
                todo.append(k)
    return sorted(seen)


def group_file(index):
    aut = json.loads((S4 / f'certificates/aut_{index}.json').read_text())
    maps = [g['syndrome_columns'] for g in aut['generators']]
    b = len(aut['P'])
    elems = group_closure(maps, b)
    assert len(elems) == aut['graph_group_order'] or not maps, (index, len(elems), aut['graph_group_order'])
    TMP.mkdir(exist_ok=True)
    path = TMP / f'group_{index}.txt'
    nontriv = [g for g in elems if list(g) != list(range(1 << b))]
    if not nontriv:
        return None, elems
    path.write_text(f'{1 << b} {len(nontriv)}\n' + '\n'.join(' '.join(map(str, g)) for g in nontriv) + '\n')
    return path, elems


def joint_min(xs, elems):
    """Lex-min sorted affine 8-point list over suffix group x anchors (prefix S8)."""
    p = len(xs)
    dep = 0
    for v in xs:
        dep ^= v
    pts = [0, *xs, dep]
    best = None
    for g in elems:
        img = [g[v] for v in pts]
        for a in img:
            cand = sorted(v ^ a for v in img if v != a)
            if best is None or cand < best:
                best = cand
    assert len(best) == p + 1
    return best[:p]
