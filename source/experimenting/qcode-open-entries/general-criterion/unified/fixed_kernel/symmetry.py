"""Physical suffix subgroup fixing a radical-identification slice pointwise."""
from model import lift_coordinate,reduced_basis
from m8r1.suffix_symmetries import syndrome_orbits
from gauge_rankone_h5.common import first_orbits

def suffix_slice(model,N,data,context):
 key=(tuple(model.C),tuple(reduced_basis(N)),tuple(data['units']),tuple(data['Gamma']),tuple(context['radical_coeff']),context['tags'][0],model.d)
 cache=getattr(model,'_fixed_kernel_suffix_slices',None)
 if cache is None:cache={};model._fixed_kernel_suffix_slices=cache
 if key in cache:return cache[key]
 full=syndrome_orbits(model,data,N);generators=[]
 for S in full['verified_syndrome_generators']:
  if all(sum(((r&s).bit_count()%2)<<j for j,s in enumerate(S))==r for r in context['radical_coeff']):generators.append(S)
 eligible=[v for v,d in enumerate(data['distances']) if d>=model.d-1 and all((r&v).bit_count()%2==(context['tags'][0]>>j)&1 for j,r in enumerate(context['radical_coeff']))]
 orbits=first_orbits(eligible,generators)
 result=dict(eligible=eligible,first_representatives=[o['representative'] for o in orbits],orbits=orbits,generators=generators,CN_physical_group_order=full['automorphism_order'],scope='Subgroup generated by individually radical-fixing physical C,N automorphisms; may be a proper subgroup')
 cache[key]=result;return result
